import { chromium } from 'playwright';
import fs from 'node:fs';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome' });
const page = await browser.newPage({ viewport: { width: 960, height: 760 } });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message + '\n' + (e.stack ?? '')));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
const ev = (fn, ...a) => page.evaluate(fn, ...a);
const tap = async (key, n = 1, delay = 90) => { for (let i = 0; i < n; i++) { await page.keyboard.press(key); await page.waitForTimeout(delay); } };
const st = () => ev(() => { const s = window.lad.scenes.top; return { scene: s?.constructor?.name, idle: s?.runner?.done, widgets: window.lad.widgets.map((w) => w.constructor.name), waiting: window.lad.dialog.waiting, active: window.lad.dialog.active, lines: window.lad.dialog.lines }; });
await page.goto('http://localhost:5173/');
await page.waitForFunction(() => window.lad && window.lad.scenes.stack.length > 0);
await page.waitForTimeout(800);
await ev(() => { const g = window.lad.newGame(); g.flags.ch1_started = true; g.flags.king_talked = true; window.lad.director.enterLocation(g, 'guardiana', 9, 15, 'up'); });
await page.waitForTimeout(800);
console.log('0', JSON.stringify(await st()));
await tap('KeyZ'); await page.waitForTimeout(300);
console.log('1', JSON.stringify(await st()));
await tap('KeyZ'); await page.waitForTimeout(400);
console.log('2 after greeting', JSON.stringify(await st()));
await page.screenshot({ path: 'test-results/dbg-shop-1.png' });
await tap('KeyZ'); await page.waitForTimeout(400); // Buy
console.log('3 buy list', JSON.stringify(await st()));
await page.screenshot({ path: 'test-results/dbg-shop-2.png' });
await tap('ArrowDown', 5, 80); await tap('KeyZ'); await page.waitForTimeout(400);
console.log('4 who', JSON.stringify(await st()));
await page.screenshot({ path: 'test-results/dbg-shop-3.png' });
await tap('KeyZ'); await page.waitForTimeout(500);
console.log('5 bought', JSON.stringify(await st()));
await page.screenshot({ path: 'test-results/dbg-shop-4.png' });
for (let i = 0; i < 8; i++) { await tap('KeyX'); await page.waitForTimeout(300); console.log('x' + i, JSON.stringify(await st())); }
await page.screenshot({ path: 'test-results/dbg-shop-5.png' });
console.log('gold', await ev(() => window.lad.state.gold), 'items', await ev(() => window.lad.state.force[0].items));
await browser.close();
if (errors.length) console.log('ERRORS\n' + errors.join('\n'));
